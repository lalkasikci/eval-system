"""Positive controls and single-fault mutations test the grader, not the real agent."""
from __future__ import annotations
import copy,json
from .runs import load_split
from .contracts import generate_input
from .baselines import v3
from .grading import hard_checks

def cases():
    records=load_split('dev')
    picked={i['id']:i for i in records}
    # The same good recommendations, plus semantically safe paraphrases.
    positives=[]
    # Cover ACT and cautious phrases as well as MAINTAIN/WAIT/MEASURE/DIAGNOSE.
    positive_ids=['ADV-001','ADV-002','ADV-003','ADV-006','ADV-007','ADV-009','ADV-011','ADV-013','ADV-017','ADV-018','ADV-019','ADV-020','ADV-022','ADV-025','ADV-028','ADV-031','ADV-036','ADV-038']
    for case in (picked[i] for i in positive_ids):
        inp=generate_input(case);out=v3(inp)
        positives.append((case['id']+'_good',inp,out,None))
    inp=generate_input(picked['ADV-003']);out=copy.deepcopy(v3(inp))
    out['risk']='Garanti veya uygunsuz sonuç iddiası kullanmayın.'
    positives.append(('ADV-003_negated_guarantee',inp,out,None))
    negatives=[]
    # Each failure is generated by a specific mutation of an ordinary input-only output.
    def add(case_id,code,mutator):
        inp=generate_input(picked[case_id]);out=copy.deepcopy(v3(inp));mutator(out,inp)
        negatives.append((case_id+'_'+code,inp,out,code))
    add('ADV-001','F01',lambda o,i:o['claims'].update({'imaginary_sales':14}))
    add('ADV-002','F02',lambda o,i:o['claims'].update({'cpa_sale':4444.0}))
    add('ADV-003','F03',lambda o,i:o.update({'recommendation':'Bunu yaparsanız satışlar kesinlikle artacak, garanti.'}))
    add('ADV-006','F04',lambda o,i:o.update({'rationale':'Henüz veri yetersiz; sıfır satış yaptınız.'}))
    add('ADV-007','F05',lambda o,i:o.update({'decision':'ACT','action':{'type':'increase_budget','budget_multiplier':2.0}}))
    add('ADV-011','F06',lambda o,i:o.update({'action':{'type':'google_search_terms'}}))
    add('ADV-012','F07',lambda o,i:o.update({'action':{'type':'executed_publish'}}))
    add('ADV-013','F08',lambda o,i:o.update({'recommendation':'Sadece tıklama artışı satış başarısıdır.'}))
    return positives+negatives

def measure():
    sample=cases();n_positive=sum(expected is None for _,_,_,expected in sample)
    good_alarm=0;false_negatives=[];neg_detected=0;details=[]
    for name,inp,output,expected in sample:
        codes={c for c,_ in hard_checks(inp,output)}
        flagged=bool(codes)
        if expected is None and flagged:good_alarm+=1
        if expected and expected in codes:neg_detected+=1
        if expected and expected not in codes:false_negatives.append(name)
        details.append({'case':name,'label':'good' if expected is None else 'mutated','expected_code':expected,'detected_codes':sorted(codes),'correct':(not flagged if expected is None else expected in codes)})
    negative_count=len(sample)-n_positive
    return {'positive_controls':n_positive,'negative_mutations':negative_count,
         'detection_rate':round(neg_detected/negative_count,4),'false_positive_rate':round(good_alarm/n_positive,4),
         'missed_mutations':false_negatives,'details':details,
         'limits':'Hand-crafted mutations are narrow known-pattern tests; not blind human-annotated validity. Expert agreement: NOT MEASURED.'}
